#' Fit Generalized Linear Model (GLM) with Catalytic Prior
#'
#' This function fits a GLM with a catalytic prior on the regression coefficients. It uses
#' information provided by the `cat_init` object generated during initialization to incorporate
#' both observed and synthetic data. The model is fitted using the specified `formula`, `family`,
#' and a single `tau` value to downweight synthetic data. The resulting `cat_glm` object encapsulates
#' the fitted model, including estimated coefficients and family information, facilitating further analysis.
#'
#' @param formula Formula describing the model to be fit. See `stats::glm` for details on formula syntax.
#' @param family GLM family to use. If not specified, defaults to `cat_init$family`.
#' @param cat_init Object containing initialized data and settings generated by `catalytic::cat_glm_initialization`.
#' @param tau Single numeric value for downweighting synthetic data. Defaults to one forth of the number of predictors.
#' @param ... Additional arguments passed to `stats::glm` for model fitting.
#'
#' @return An object of class `cat_glm` containing:
#'   \item{function_name}{Function name.}
#'   \item{formula}{Formula used for modeling. Default `cat_init`$family}
#'   \item{family}{GLM family used.}
#'   \item{cat_init}{Initialized data object from `cat_glm_initialization`.}
#'   \item{tau}{Tau value used for downweighting synthetic data.}
#'   \item{model}{Fitted GLM model object with `tau`.}
#'   \item{coefficients}{Estimated coefficients from the `model`.}
#'
#' @export
#'
#' @seealso
#' \code{\link{cat_glm_initialization}}}
cat_glm <- function(formula,
                    cat_init,
                    tau = NULL) {
  # Validate Input Parameters
  validate_glm_input(
    formula = formula,
    cat_init = cat_init,
    tau = tau
  )

  # Update cat_init with adjusted data based on the formula's right-hand side
  f_rhs <- get_formula_rhs(formula, with_tilde = TRUE)
  full_formula <- as.formula(paste0(cat_init$y_col_name, f_rhs))

  cat_init <- get_adjusted_cat_init(
    cat_init = cat_init,
    formula_rhs = f_rhs
  )


  if (is.null(tau)) {
    tau <- ifelse(
      cat_init$family == "gaussian",
      ncol(cat_init$adj_x) / 4,
      ncol(cat_init$adj_x)
    )
  }

  # Perform Catalytic Fitting
  glm_model <- do.call(
    stats::glm,
    list(
      formula = full_formula,
      family = cat_init$family,
      data = cat_init$data,
      weights = c(
        rep(1, cat_init$obs_size),
        rep(tau / cat_init$syn_size, cat_init$syn_size)
      )
    )
  )


  # Finalize Setup and Output
  cat_model <- list(
    function_name = "cat_glm",
    ## Input/Processed parameters
    formula = full_formula,
    cat_init = cat_init,
    tau = tau,
    ## Result
    model = glm_model,
    coefficients = coef(glm_model)
  )

  class(cat_model) <- c(cat_model$class, "cat_glm")

  return(cat_model)
}
