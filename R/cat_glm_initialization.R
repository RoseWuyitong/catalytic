#' Initialize data for catalytic Generalized linear models (GLM)
#'
#' This function initializes data for fitting Generalized linear models (GLM) with synthetic data using the catalytic package.
#' Adjust parameters such as the formula, family, and syn_size to customize the initialization process.
#'
#' @param formula A formula specifying the simple model structure, which is used for generating synthetic responses.
#'                See `stats::glm` for details on formula syntax.
#' @param family The type of GLM family. Defaults to Gaussian. Specify `binomial` for logistic regression.
#' @param data The original dataset in `data.frame` format.
#' @param syn_size The size of synthetic data to generate. Defaults to 4 times the number of columns in `data`.
#' @param ... Additional arguments passed to the `stats::glm` function when fitting the simple model.
#' @param resample_only Logical indicating whether to generate synthetic data only by resampling original data. Defaults to `FALSE`.
#' @param x_degree Determines the degree of the polynomial terms for the predictors in the model, which affects the diversity or complexity of the predictor terms included. Defaults to `NULL`, which means the degree for all predictors is 1.
#' @param na_replace Function used to handle missing values in the original dataset. Defaults to `stats::na.omit`.
#'
#' @return An object of class `cat_init` containing the following elements:
#'   \describe{
#'     \item{function_name}{Name of the initialization function.}
#'     \item{formula}{The formula used for model initialization, specifying the relationship between predictors and response variables.}
#'     \item{family}{The GLM family type used (e.g., Binomial, Gaussian).}
#'     \item{y_col_name}{The response variable column name.}
#'     \item{obs_size}{The size (number of rows) of the original dataset.}
#'     \item{obs_data}{The original dataset, which includes both predictors and response variables.}
#'     \item{obs_x}{The predictors (covariates) extracted from the original dataset.}
#'     \item{obs_y}{The response variable(s) extracted from the original dataset.}
#'     \item{syn_size}{The size (number of rows) of the synthetic dataset generated based on resampling.}
#'     \item{syn_data}{The synthetic dataset, which includes both the resampled covariates and the generated response values.}
#'     \item{syn_x}{The synthetic covariates generated by resampling the original covariates.}
#'     \item{syn_y}{The synthetic responses generated by applying the GLM model to the synthetic covariates.}
#'     \item{syn_x_resample_inform}{Additional information about the resampling process used to generate synthetic covariates (e.g., resampling methods applied).}
#'     \item{size}{The total size of the combined dataset, which is the sum of the original dataset size and the synthetic dataset size.}
#'     \item{data}{The combined dataset, containing both the original observations and the generated synthetic data.}
#'     \item{x}{The combined covariates (predictors) from both the original and synthetic datasets.}
#'     \item{y}{The combined responses from both the original and synthetic datasets.}
#'     \item{...}{All arguments passed into this function.}
#'   }
#'
#' @export
#'
#' @examples
#' data("binomial_swim")
#' swim_data <- cbind(binomial_swim$x, binomial_swim$y)
#'
#' # Initialize data for GLM Logistic Regression
#' cat_init <- cat_glm_initialization(
#'   formula = empyr1 ~ 1,
#'   family = binomial,
#'   data = swim_data,
#'   syn_size = 1000,
#'   resample_only = FALSE
#' )
#'
#' cat_init
cat_glm_initialization <- function(formula,
                                   family = gaussian(),
                                   data,
                                   syn_size = NULL,
                                   custom_variance = NULL,
                                   x_degree = NULL,
                                   resample_only = FALSE,
                                   na_replace = stats::na.omit) {
  # Validate Input Parameters
  validate_glm_initialization_input(
    formula = formula,
    family = family,
    data = data,
    syn_size = syn_size,
    custom_variance = custom_variance,
    x_degree = x_degree
  )

  # Extract Information from Input Parameters
  ## Standardize observation covariate and response
  obs_data <- get_standardized_data(
    data = data,
    na_replace = na_replace
  )

  ## Extract observation covariate and response
  y_col_name <- get_formula_lhs(formula)
  obs_x <- as.data.frame(obs_data[, c(setdiff(names(obs_data), c(y_col_name))), drop = FALSE])
  obs_y <- obs_data[, y_col_name]

  # Generate Synthetic Dataset
  if (is.null(x_degree)) x_degree <- rep(1, (ncol(obs_x)))
  if (is.null(syn_size)) syn_size <- (ncol(data) - 1) * 4

  ## Generate synthetic covariate by resampling observation covariate
  syn_x_inform <- get_resampled_data(
    data = obs_x,
    resample_size = syn_size,
    data_degree = x_degree,
    resample_only = resample_only
  )
  syn_x <- as.data.frame(syn_x_inform$resampled_data)

  ## Generate synthetic response by using simple model
  simple_model <- stats::glm(
    formula = formula,
    family = family,
    data = obs_data
  )

  family <- get_glm_family_string(family)

  syn_y <- if (family == "binomial") {
    stats::rbinom(syn_size, 1, stats::predict(simple_model, syn_x, type = "response"))
  } else {
    stats::predict(simple_model, syn_x)
  }

  # Finalize Setup and Output
  cat_init <- list(
    function_name = "cat_glm_initialization",
    ## Input/Processed parameters
    formula = formula,
    family = family,
    syn_size = syn_size,
    custom_variance = if (family == "gaussian") custom_variance else 0,
    x_degree = x_degree,
    resample_only = resample_only,
    na_replace = na_replace,
    y_col_name = y_col_name,
    simple_model = simple_model,
    ## Observation data information
    obs_size = nrow(obs_data),
    obs_data = obs_data,
    obs_x = obs_x,
    obs_y = obs_y,
    ## Synthetic data information
    syn_size = syn_size,
    syn_data = cbind(syn_x, setNames(as.data.frame(syn_y), y_col_name)),
    syn_x = syn_x,
    syn_y = syn_y,
    syn_x_resample_inform = syn_x_inform$resampled_data_record
  )

  cat_init <- c(
    cat_init,
    list(
      ## Whole data information
      size = cat_init$obs_size + cat_init$syn_size,
      data = rbind(cat_init$obs_data, cat_init$syn_data),
      x = rbind(cat_init$obs_x, cat_init$syn_x),
      y = c(cat_init$obs_y, cat_init$syn_y)
    )
  )

  class(cat_init) <- c(cat_init$class, "cat_initialization")

  return(cat_init)
}
