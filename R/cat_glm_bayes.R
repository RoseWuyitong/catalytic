#' Bayesian Generalized Linear Model (GLM) with Catalytic Prior
#'
#' This function fits a Bayesian GLM with a catalytic prior on the regression coefficients. It uses
#' information provided by the `cat_init` object generated during initialization to incorporate both
#' observed and synthetic data. The model is fitted using Stan through the specified formula, GLM `family`,
#' and a single `tau` value to downweight synthetic data. The resulting `cat_glm_bayes` object encapsulates
#' the fitted model, including estimated coefficients and Stan sampling information, facilitating further analysis.
#'
#' @param formula Formula describing the model to be fit. See `stats::glm` for details on formula syntax.
#' @param family GLM family to use. If not specified, defaults to `cat_init$family`.
#' @param cat_init Object containing initialized data and settings generated by `catalytic::cat_glm_initialization`.
#' @param tau Single numeric value for downweighting synthetic data. Defaults to one fourth of the number of predictors.
#' @param ... Additional arguments passed to `rstan::sampling` for model fitting.
#' @param stan_chains Number of Markov chains to run. Defaults to 4.
#' @param stan_iter Total number of iterations per chain (including warmup). Defaults to 2000.
#' @param stan_warmup Number of warmup iterations per chain. Defaults to 1000.
#' @param stan_algorithm Sampling algorithm to use, e.g., "HMC" (Hamiltonian Monte Carlo). Defaults to "NUTS".
#'
#' @return An object of class `cat_glm_bayes` containing:
#'   \item{function_name}{Function name.}
#'   \item{formula}{Formula used for modeling.}
#'   \item{family}{GLM family used.}
#'   \item{cat_init}{Initialized data object from `cat_glm_initialization`.}
#'   \item{tau}{Tau value used for downweighting synthetic data.}
#'   \item{stan_chains}{Number of chains used in Stan sampling.}
#'   \item{stan_iter}{Total number of iterations per chain.}
#'   \item{stan_warmup}{Number of warmup iterations per chain.}
#'   \item{stan_algorithm}{Sampling algorithm used.}
#'   \item{stan_model}{Compiled Stan model object.}
#'   \item{stan_sample_model}{Stan sampling object containing the posterior samples.}
#'   \item{coefficients}{Estimated coefficients from the posterior samples.}
#'
#' @export
#'
#' @examples
#' @seealso
#' \code{\link{cat_glm_initialization}}

cat_glm_bayes <- function(
    formula,
    family = NULL,
    cat_init,
    tau = NULL,
    ...,
    stan_chains = 4,
    stan_iter = 2000,
    stan_warmup = 1000,
    stan_algorithm = "NUTS") {
  if (!is.cat_glm_init(cat_init)) {
    stop(
      "Please enter `cat_init` that generated from `catalytic::cat_glm_initialization`."
    )
  }

  f_rhs <- get_formula_rhs(formula, with_tilde = TRUE)
  f_lhs <- get_formula_lhs(formula)
  if (f_lhs != "NULL" & f_lhs != colnames(cat_init$y)) stop("Please enter the correct y name for formula.")

  cat_init <- get_adjusted_data(cat_init = cat_init, formula = formula)

  if (is.null(family)) family <- cat_init$family
  if (is.null(tau)) tau <- ncol(cat_init$adj_x) / 4
  if (tau < 0) stop("Please enter non-negative `tau` value.")

  stan_data <- list(
    obs_n = cat_init$obs_size,
    syn_n = cat_init$syn_size,
    col_n = ncol(cat_init$adj_x),
    obs_x = cat_init$adj_obs_x,
    syn_x = cat_init$adj_syn_x,
    obs_y = as.vector(cat_init$obs_y),
    syn_y = as.vector(cat_init$syn_y),
    tau = tau
  )

  stan_model <- get_stan_model(
    type = "glm",
    glm_family = family
  )


  stan_sample_model <- rstan::sampling(
    object = stan_model,
    data = stan_data,
    chains = stan_chains,
    iter = stan_iter,
    warmup = stan_warmup,
    algorithm = stan_algorithm,
    ...
  )

  coefs <- rstan::summary(stan_sample_model)$summary[
    grep("coefs", rownames(rstan::summary(stan_sample_model)$summary)),
    "mean"
  ]


  if (!is.null(coefs)) {
    names(coefs) <- c("(Intercept)", colnames(cat_init$adj_x))
  }
  cat_glm_bayes_ <- list(
    function_name = "cat_glm_bayes",
    formula = as.formula(paste0(colnames(cat_init$y), f_rhs)),
    family = family,
    cat_init = cat_init,
    tau = tau,
    stan_chains = stan_chains,
    stan_iter = stan_iter,
    stan_warmup = stan_warmup,
    stan_algorithm = stan_algorithm,
    stan_model = stan_model,
    stan_sample_model = stan_sample_model,
    coefficients = coefs,
    ...
  )

  class(cat_glm_bayes_) <- c(cat_glm_bayes_$class, "cat_glm_bayes", "bayes")

  return(cat_glm_bayes_)
}
